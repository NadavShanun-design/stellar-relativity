"""Render a single-star relativity report as a standalone HTML page."""

from __future__ import annotations

from html import escape

from .catalog import find
from .report import DEFAULT_OBSERVATION_YEAR, report_lines

_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>{title} · stellar-relativity</title>
<style>
  body {{ background:#05060d; color:#e8ecff; font-family:ui-monospace,Menlo,monospace;
          display:flex; justify-content:center; padding:40px 16px; }}
  .card {{ background:#0d1024; border:1px solid #1d2142; border-radius:14px;
           padding:28px 32px; max-width:640px; width:100%; }}
  h1 {{ margin:0 0 4px; font-size:22px; }}
  .accent {{ color:#ffd166; }}
  pre {{ white-space:pre-wrap; line-height:1.55; margin:12px 0 0; font-size:14px; }}
  footer {{ color:#8b93c0; font-size:12px; margin-top:18px; }}
</style>
</head>
<body>
  <div class="card">
    <h1 class="accent">{title}</h1>
    <pre>{body}</pre>
    <footer>Generated by stellar-relativity · cruising at {pct:.1f}% of light speed</footer>
  </div>
</body>
</html>
"""


def star_html(name: str, beta: float = 0.9, observation_year: int = DEFAULT_OBSERVATION_YEAR) -> str:
    """Return a complete HTML document reporting on the named star."""
    star = find(name)
    lines = report_lines(star, beta=beta, observation_year=observation_year)
    body = escape("\n".join(lines))
    return _TEMPLATE.format(title=escape(star.name), body=body, pct=beta * 100)


__all__ = ["star_html"]
